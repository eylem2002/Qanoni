import * as z from "zod";
import type { ContractTemplate } from "./types";

/* ══════════════════════════════════════════════════════════
   RENTAL CONTRACT TEMPLATE (عقد إيجار)

   Governing law: القانون المدني الأردني رقم (43) لسنة 1976 وتعديلاته،
   وقانون إيجار العقارات الأردني رقم (11) لسنة 1994 وتعديلاته.

   ⚠️ LAWYER REVIEW REQUIRED ⚠️ — fixed statutory clauses below are a grounded
   starting point and must be approved by a licensed Jordanian lawyer.
══════════════════════════════════════════════════════════ */

export const RentalBody = z.object({
  landlordName: z.string().min(2).max(200),
  tenantName: z.string().min(2).max(200),
  propertyAddress: z.string().min(4).max(500),
  propertyType: z.enum(["شقة", "فيلا", "محل تجاري", "مستودع", "مكتب"]),
  monthlyRent: z.coerce.number().positive().max(1_000_000),
  contractDurationMonths: z.coerce.number().int().min(1).max(120).default(12),
  startDate: z.string().min(2).max(50),
  depositAmount: z.coerce.number().min(0).max(1_000_000).default(0),
  paymentDayOfMonth: z.coerce.number().int().min(1).max(28).default(1),
  furnitureStatus: z.enum(["مفروش", "نصف مفروش", "غير مفروش"]),
  specialConditions: z.string().max(1000).optional(),
});

export type RentalData = z.infer<typeof RentalBody>;

export const rentalTemplate: ContractTemplate<RentalData> = {
  type: "rental",
  title: () => "عقد إيجار عقار",

  preamble: (d) =>
    `حُرِّر هذا العقد استناداً إلى أحكام القانون المدني الأردني رقم (43) لسنة 1976 وقانون إيجار العقارات رقم (11) لسنة 1994 وتعديلاتهما، بين كلٍّ من:

الطرف الأول (المؤجر): ${d.landlordName}.
الطرف الثاني (المستأجر): ${d.tenantName}.

وقد اتفق الطرفان وهما بكامل الأهلية القانونية على ما يلي:`,

  clauses: [
    {
      kind: "fixed",
      id: "property",
      heading: "البند الأول: العقار المؤجَّر",
      render: (d) =>
        `أجّر الطرف الأول إلى الطرف الثاني العقار الكائن في: ${d.propertyAddress}، ونوعه: ${d.propertyType}، وحالته: ${d.furnitureStatus}. ` +
        `وقد عاين المستأجر العقار المعاينة النافية للجهالة وقبله بحالته الراهنة.`,
    },
    {
      kind: "fixed",
      id: "duration",
      heading: "البند الثاني: مدة الإيجار",
      render: (d) =>
        `مدة هذا العقد (${d.contractDurationMonths}) شهراً تبدأ من تاريخ ${d.startDate}. ` +
        `ويتجدد العقد بالتراضي بين الطرفين، ولأي طرف عدم رغبته في التجديد بإشعار خطّي مسبق للطرف الآخر وفقاً للقانون.`,
    },
    {
      kind: "fixed",
      id: "rent",
      heading: "البند الثالث: بدل الإيجار وآلية الدفع",
      render: (d) =>
        `بدل الإيجار الشهري (${d.monthlyRent}) ديناراً أردنياً، يُدفع في اليوم (${d.paymentDayOfMonth}) من كل شهر مقدماً عن طريق وسيلة دفع موثّقة. ` +
        `ويُعدّ تأخر المستأجر عن الدفع وفقاً للمواعيد المتفق عليها إخلالاً يجيز للمؤجر المطالبة بالإخلاء وفقاً لأحكام قانون إيجار العقارات.`,
    },
    {
      kind: "fixed",
      id: "deposit",
      heading: "البند الرابع: مبلغ التأمين",
      render: (d) =>
        d.depositAmount > 0
          ? `دفع المستأجر مبلغ تأمين مقداره (${d.depositAmount}) ديناراً أردنياً، يُرَدّ إليه عند إخلاء العقار وتسليمه بحالة جيدة بعد خصم أي مستحقات أو أضرار غير ناشئة عن الاستعمال المعتاد.`
          : `لا يوجد مبلغ تأمين متفق عليه في هذا العقد.`,
    },
    {
      kind: "fixed",
      id: "maintenance",
      heading: "البند الخامس: الصيانة والإصلاحات",
      render: () =>
        `تقع على عاتق المؤجر الصيانة الأساسية والإصلاحات الجوهرية للعقار (الإنشائية والمرافق الرئيسية)، ` +
        `وتقع على عاتق المستأجر الصيانة الدورية البسيطة الناشئة عن الاستعمال المعتاد. ولا يجوز للمستأجر إجراء تعديلات جوهرية على العقار دون موافقة خطّية من المؤجر.`,
    },
    {
      kind: "variable",
      id: "use_and_obligations",
      heading: "البند السادس: أوجه الاستعمال والتزامات المستأجر",
      required: true,
      instruction: (d) =>
        `صِغ بنداً يحدد استعمال العقار للغرض المخصص له (${d.propertyType}) وعدم استعماله لغير ذلك دون موافقة المؤجر، ` +
        `والتزام المستأجر بدفع فواتير الخدمات (ماء، كهرباء، وما شابه)، والمحافظة على العقار، وعدم تأجيره من الباطن دون موافقة خطّية، مع الالتزام بالقوانين والأنظمة ذات العلاقة.`,
    },
    {
      kind: "fixed",
      id: "eviction",
      heading: "البند السابع: الإخلاء وفسخ العقد",
      render: () =>
        `يلتزم المستأجر بإخلاء العقار وتسليمه للمؤجر بحالة جيدة عند انتهاء مدة العقد أو فسخه. ` +
        `ويجوز لأي من الطرفين طلب فسخ العقد عند إخلال الطرف الآخر بالتزاماته الجوهرية بعد إنذاره، وذلك وفقاً لأحكام قانون إيجار العقارات والقانون المدني الأردني، وتختص المحاكم الأردنية بالنظر في النزاعات.`,
    },
    {
      kind: "variable",
      id: "special_conditions",
      heading: "البند الثامن: شروط خاصة",
      required: false,
      instruction: (d) =>
        d.specialConditions?.trim()
          ? `صِغ الشروط الخاصة التالية بصياغة قانونية سليمة دون مخالفة القانون الأردني: "${d.specialConditions.trim()}".`
          : `اكتب: "لا توجد شروط خاصة إضافية خارج ما ورد في هذا العقد."`,
    },
    {
      kind: "fixed",
      id: "general",
      heading: "البند التاسع: أحكام عامة",
      render: () =>
        `كل ما لم يرد بشأنه نص في هذا العقد تسري عليه أحكام القانون المدني الأردني وقانون إيجار العقارات والتشريعات النافذة. ` +
        `وحُرِّر هذا العقد من نسختين أصليتين بيد كل طرف نسخة للعمل بموجبها.`,
    },
  ],

  signatureBlock: () =>
    `التوقيعات

الطرف الأول (المؤجر): ___________________________    التاريخ: ________________
الطرف الثاني (المستأجر): ___________________________   التاريخ: ________________`,

  disclaimer:
    "تنبيه: هذا العقد مُولَّد بمساعدة الذكاء الاصطناعي استناداً إلى القانون المدني الأردني وقانون إيجار العقارات. البنود القانونية الإلزامية فيه ثابتة وتحتاج إلى اعتماد محامٍ أردني مرخص. يُنصح بمراجعة محامٍ مرخص قبل التوقيع.",
};

export const RENTAL_REQUIRED = ["المؤجر", "المستأجر", "بدل الإيجار", "التوقيعات"];
