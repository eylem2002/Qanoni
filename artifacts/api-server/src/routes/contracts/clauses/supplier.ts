import * as z from "zod";
import type { ContractTemplate } from "./types";

/* ══════════════════════════════════════════════════════════
   SUPPLIER CONTRACT TEMPLATE (عقد توريد)

   Governing law: القانون المدني الأردني رقم (43) لسنة 1976 وتعديلاته،
   وقانون التجارة الأردني رقم (12) لسنة 1966 وتعديلاته.

   ⚠️ LAWYER REVIEW REQUIRED ⚠️ — fixed statutory clauses below are a grounded
   starting point and must be approved by a licensed Jordanian lawyer.
══════════════════════════════════════════════════════════ */

export const SupplierBody = z.object({
  buyerName: z.string().min(2).max(200),
  supplierName: z.string().min(2).max(200),
  goodsOrServices: z.string().min(10).max(2000),
  totalContractValue: z.coerce.number().positive().max(100_000_000),
  paymentTerms: z.string().min(2).max(200),
  deliverySchedule: z.string().min(2).max(500),
  deliveryLocation: z.string().min(2).max(500),
  warrantyPeriodDays: z.coerce.number().int().min(0).max(3650).default(30),
  penaltyForDelay: z.coerce.number().min(0).max(100).optional(),
  hasExclusivity: z.boolean().default(false),
  specialConditions: z.string().max(1000).optional(),
});

export type SupplierData = z.infer<typeof SupplierBody>;

export const supplierTemplate: ContractTemplate<SupplierData> = {
  type: "supplier",
  title: () => "عقد توريد",

  preamble: (d) =>
    `حُرِّر هذا العقد استناداً إلى أحكام القانون المدني الأردني رقم (43) لسنة 1976 وقانون التجارة الأردني وتعديلاتهما، بين كلٍّ من:

الطرف الأول (المشتري): ${d.buyerName}.
الطرف الثاني (المورّد): ${d.supplierName}.

وقد اتفق الطرفان وهما بكامل الأهلية القانونية على ما يلي:`,

  clauses: [
    {
      kind: "variable",
      id: "subject",
      heading: "البند الأول: موضوع العقد",
      required: true,
      instruction: (d) =>
        `صِغ بنداً يحدد البضائع أو الخدمات المطلوب توريدها ومواصفاتها استناداً إلى ما يلي: "${d.goodsOrServices}"، بشكل واضح ومحدد يمنع الجهالة.`,
    },
    {
      kind: "fixed",
      id: "delivery",
      heading: "البند الثاني: جدول التوريد ومكان التسليم",
      render: (d) =>
        `يلتزم المورّد بالتوريد وفق الجدول التالي: ${d.deliverySchedule}، ويتم التسليم في: ${d.deliveryLocation}. ` +
        `ويُعدّ التسليم منجزاً عند تسليم البضاعة في المكان المتفق عليه وقبولها وفق آلية الفحص الواردة في هذا العقد.`,
    },
    {
      kind: "fixed",
      id: "price_payment",
      heading: "البند الثالث: القيمة وشروط الدفع",
      render: (d) =>
        `القيمة الإجمالية للعقد (${d.totalContractValue}) ديناراً أردنياً، تُدفع وفق الشروط التالية: ${d.paymentTerms}. ` +
        `ويُعدّ تأخر المشتري عن الدفع في مواعيده إخلالاً يجيز للمورّد المطالبة بحقوقه وفقاً للقانون.`,
    },
    {
      kind: "fixed",
      id: "inspection",
      heading: "البند الرابع: الفحص والاستلام وحق الرفض",
      render: () =>
        `يحق للمشتري فحص البضاعة الموردة عند التسليم للتأكد من مطابقتها للمواصفات المتفق عليها، وله رفض البضاعة غير المطابقة أو المعيبة خلال مدة معقولة، ` +
        `ويلتزم المورّد باستبدالها أو إصلاحها أو رد قيمتها وفقاً لأحكام القانون المدني الأردني وقانون التجارة.`,
    },
    {
      kind: "fixed",
      id: "warranty",
      heading: "البند الخامس: الضمان",
      render: (d) =>
        d.warrantyPeriodDays > 0
          ? `يضمن المورّد البضاعة الموردة ضد العيوب الخفية وعدم المطابقة لمدة (${d.warrantyPeriodDays}) يوماً من تاريخ التسليم، ويلتزم خلالها بإصلاح أو استبدال المعيب على نفقته.`
          : `لا يتضمن هذا العقد فترة ضمان تعاقدية محددة، مع بقاء أحكام ضمان العيوب الخفية المقررة في القانون المدني الأردني سارية.`,
    },
    {
      kind: "fixed",
      id: "delay_penalty",
      heading: "البند السادس: غرامة التأخير",
      render: (d) =>
        d.penaltyForDelay && d.penaltyForDelay > 0
          ? `في حال تأخر المورّد عن مواعيد التوريد المتفق عليها دون عذر مشروع، يستحق المشتري غرامة تأخير بنسبة (${d.penaltyForDelay}%) من قيمة العقد عن كل يوم تأخير، ` +
            `بما لا يجاوز نسبة معقولة من قيمة العقد، ولمحكمة الموضوع تعديل الغرامة وفقاً لأحكام القانون المدني الأردني.`
          : `في حال تأخر المورّد عن مواعيد التوريد دون عذر مشروع، يستحق المشتري التعويض عن الضرر الفعلي وفقاً لأحكام القانون المدني الأردني.`,
    },
    {
      kind: "fixed",
      id: "risk_transfer",
      heading: "البند السابع: انتقال المخاطر والملكية",
      render: () =>
        `تنتقل ملكية البضاعة ومخاطر هلاكها إلى المشتري عند تسليمها فعلياً في المكان المتفق عليه وقبولها، ما لم يتفق الطرفان كتابةً على خلاف ذلك، وفقاً لأحكام القانون المدني الأردني.`,
    },
    {
      kind: "fixed",
      id: "force_majeure",
      heading: "البند الثامن: القوة القاهرة",
      render: () =>
        `لا يُسأل أي من الطرفين عن الإخلال بالتزاماته إذا كان ذلك ناشئاً عن قوة قاهرة خارجة عن إرادته يتعذّر دفعها أو توقّعها، ` +
        `على أن يُخطر الطرف الآخر بها فور حدوثها ويتخذ ما يلزم للحد من آثارها، وفقاً لأحكام القانون المدني الأردني.`,
    },
    {
      kind: "variable",
      id: "exclusivity",
      heading: "البند التاسع: الحصرية",
      required: false,
      instruction: (d) =>
        d.hasExclusivity
          ? `صِغ بند حصرية يلتزم بموجبه المورّد بعدم التعامل مع منافسي المشتري في ذات نطاق التوريد خلال مدة العقد، بصياغة معقولة ومحددة لا تخالف قواعد المنافسة في القانون الأردني.`
          : `اكتب: "هذا العقد غير حصري، ويجوز لكل طرف التعامل مع الغير دون قيد ما لم يرد نص خاص بخلاف ذلك."`,
    },
    {
      kind: "variable",
      id: "special_conditions",
      heading: "البند العاشر: شروط خاصة",
      required: false,
      instruction: (d) =>
        d.specialConditions?.trim()
          ? `صِغ الشروط الخاصة التالية بصياغة قانونية سليمة دون مخالفة القانون الأردني: "${d.specialConditions.trim()}".`
          : `اكتب: "لا توجد شروط خاصة إضافية خارج ما ورد في هذا العقد."`,
    },
    {
      kind: "fixed",
      id: "general",
      heading: "البند الحادي عشر: أحكام عامة وتسوية النزاعات",
      render: () =>
        `كل ما لم يرد بشأنه نص في هذا العقد تسري عليه أحكام القانون المدني الأردني وقانون التجارة. ويسعى الطرفان لحل أي نزاع ودياً، وعند تعذّر ذلك تختص المحاكم الأردنية بالنظر فيه. ` +
        `وحُرِّر هذا العقد من نسختين أصليتين بيد كل طرف نسخة للعمل بموجبها.`,
    },
  ],

  signatureBlock: () =>
    `التوقيعات

الطرف الأول (المشتري): ___________________________    التاريخ: ________________
الطرف الثاني (المورّد): ___________________________     التاريخ: ________________`,

  disclaimer:
    "تنبيه: هذا العقد مُولَّد بمساعدة الذكاء الاصطناعي استناداً إلى القانون المدني الأردني وقانون التجارة. البنود القانونية الإلزامية فيه ثابتة وتحتاج إلى اعتماد محامٍ أردني مرخص. يُنصح بمراجعة محامٍ مرخص قبل التوقيع.",
};

export const SUPPLIER_REQUIRED = ["المشتري", "المورّد", "موضوع العقد", "التوقيعات"];
